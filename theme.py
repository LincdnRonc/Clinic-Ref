import re, os, pathlib
os.chdir(pathlib.Path(__file__).resolve().parent)
P = {  # gid: (label, light accent)
 'breast':'#ad2f68','cns':'#6b3fa8','gi':'#a14a0b','gu':'#1d5fb0','gyn':'#0d7366',
 'heme':'#9b1c3f','hn':'#006f8e','sarcoma':'#5a6b10','thorax':'#2b7a3e','pall':'#4f5f74','contouring':'#0d5d78','mrl':'#7a5c00','exam':'#3a44a6'}
def hx(c): return [int(c[i:i+2],16) for i in (1,3,5)]
def tohex(v): return '#'+''.join(f'{max(0,min(255,round(x))):02x}' for x in v)
def mix(a,b,t): a,b=hx(a),hx(b); return tohex([a[i]*(1-t)+b[i]*t for i in range(3)])
def lum(c):
    r=[]
    for x in hx(c):
        x/=255; r.append(x/12.92 if x<=0.03928 else ((x+0.055)/1.055)**2.4)
    return 0.2126*r[0]+0.7152*r[1]+0.0722*r[2]
def cr(a,b):
    la,lb=sorted([lum(a),lum(b)],reverse=True); return (la+0.05)/(lb+0.05)
out=['/* ---- Tumour-site colour themes (generated by theme.py) ---- */']
dk=[];dk2=[]
for g,c in P.items():
    soft=mix(c,'#ffffff',0.9); d=mix(c,'#ffffff',0.5); dsoft=mix(c,'#162028',0.78)
    print(g, 'txt/white %.1f'%cr(c,'#ffffff'), 'txt/soft %.1f'%cr(c,soft), 'dark txt/panel %.1f'%cr(d,'#162028'), 'dark chip %.1f'%cr('#162028',d))
    out.append(f'[data-site="{g}"]{{--accent:{c};--accent-soft:{soft}}}')
    dk.append(f':root:not([data-theme="light"])[data-site="{g}"],:root:not([data-theme="light"]) [data-site="{g}"]{{--accent:{d};--accent-soft:{dsoft}}}')
    dk2.append(f':root[data-theme="dark"][data-site="{g}"],:root[data-theme="dark"] [data-site="{g}"]{{--accent:{d};--accent-soft:{dsoft}}}')
out.append('@media (prefers-color-scheme: dark){'+''.join(dk)+'}')
out+=dk2
out.append('''html[data-site] .top{border-top:5px solid var(--accent)}
html[data-site] h1 span{color:var(--accent)}
.group-title[data-site]{color:var(--accent);border-bottom:3px solid var(--accent);padding-bottom:4px}
.group-title[data-site]::before{content:"";display:inline-block;width:.7em;height:.7em;border-radius:50%;background:var(--accent);margin-right:.4em;vertical-align:.05em}
.sitenav a[data-site]{border-left:4px solid var(--accent)}
.xref[data-site],.xref{border-left:4px solid var(--accent)}
.hubcard[data-site] h3{color:var(--accent)}
footer{border-top:3px solid var(--accent)}''')
out.append('/* ---- end site themes ---- */')
css=open('assets/site.css').read()
css=re.sub(r'/\* ---- Tumour-site colour themes.*?/\* ---- end site themes ---- \*/\n?','',css,flags=re.S)
open('assets/site.css','w').write(css.rstrip()+'\n'+'\n'.join(out)+'\n')
