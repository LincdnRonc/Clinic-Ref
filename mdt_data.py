"""MDT decision matrices (rendered by build.py -> "MDT decision matrix" tab and mdt.html).

Each matrix = fields (what the MDT is told) + rows (scenarios). A row shows while every
field it names is either unanswered or answered with one of the listed options.
  when   dict {field: [options]} or a list of such dicts (any one may fit)
  strict True = modifier row: shown only once its fields are actually answered
Text mark-up: {60/20} = dose chip, [[TRIAL|2016]] = trial with year. Everything else is escaped.
Content summarises the tumour-site pages; anything not on those pages is marked (check)
and listed in the Project doc claude/figures-to-verify.md.
"""

def F(id, label, opts, show=None):
    return dict(id=id, label=label, opts=opts, show=show)

def R(title, grp, when, rec, alt='', rt='', ev='', ask='', more=None, strict=False):
    return dict(title=title, grp=grp, when=when, rec=rec, alt=alt, rt=rt, ev=ev, ask=ask, more=more, strict=strict)

